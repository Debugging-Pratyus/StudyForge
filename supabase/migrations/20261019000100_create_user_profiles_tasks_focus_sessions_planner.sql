create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  theme text default 'system',
  created_at timestamptz default now()
);

create table if not exists public.tasks (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  subject text,
  planned_minutes integer default 25,
  due_date date,
  completed boolean default false,
  completed_at timestamptz,
  created_at timestamptz default now()
);

create table if not exists public.focus_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  duration_minutes integer not null,
  completed_at timestamptz default now()
);

create table if not exists public.planner (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  plan_date date not null,
  goal text default '',
  minutes integer default 0,
  created_at timestamptz default now(),
  constraint planner_user_id_plan_date_key unique (user_id, plan_date)
);

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.planner'::regclass
      and conname = 'planner_user_id_plan_date_key'
      and contype = 'u'
  ) then
    alter table public.planner
      add constraint planner_user_id_plan_date_key unique (user_id, plan_date);
  end if;
end
$$;

